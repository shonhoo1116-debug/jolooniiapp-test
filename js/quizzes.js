// «Тэмдэг таних»: тэмдгийн санд зурагдсан тэмдгүүдээс санамсаргүй 10 асуулт үүсгэнэ.
function makeSignQuiz(n = 10) {
  const pool = SIGNS.filter(s => SG.has(s.code) && s.group <= 6);
  const pick = [...pool].sort(() => Math.random() - .5);
  const chosen = [], names = new Set();
  for (const s of pick) { if (chosen.length >= n) break; if (names.has(s.name)) continue; names.add(s.name); chosen.push(s); }
  const questions = chosen.map(s => {
    const same = pool.filter(x => x.group === s.group && x.name !== s.name);
    const others = pool.filter(x => x.group !== s.group && x.name !== s.name);
    const dist = [];
    for (const x of [...same].sort(() => Math.random() - .5).concat([...others].sort(() => Math.random() - .5))) {
      if (dist.length >= 3) break; if (!dist.some(d => d.name === x.name)) dist.push(x);
    }
    const opts = [s, ...dist].sort(() => Math.random() - .5);
    return { sign: s.code, q: 'Энэ ямар тэмдэг вэ?', opts: opts.map(o => o.name), a: opts.indexOf(s),
      why: `${s.code} «${s.name}» (${SIGN_GROUPS[s.group]} тэмдэг).` };
  });
  return { id: 'q-signs', name: 'Тэмдэг таних', rule: '1-р хавсралт', section: 'signs',
    intro: 'Зурагт гарсан замын тэмдгийг таниж, нэрийг нь сонго. Санамсаргүй 10 тэмдэг.', questions };
}
